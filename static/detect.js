document.getElementById('analyze-btn').addEventListener('click', async () => {
    const fileInput = document.getElementById('audio-upload');
    const loadingText = document.getElementById('loading');
    const resultsCard = document.getElementById('results-card');

    // Make sure the user actually selected a file
    if (fileInput.files.length === 0) {
        alert('Please select an audio file first.');
        return;
    }

    const file = fileInput.files[0];

    // THE FIX 1: Strict file type validation for ALL major audio formats
    const validExtensions = ['wav', 'mp3', 'm4a', 'ogg', 'flac', 'aac', 'opus', 'webm', 'wma', 'mp4'];
    const fileExtension = file.name.split('.').pop().toLowerCase();

    if (!validExtensions.includes(fileExtension)) {
        alert(`Invalid file format. Allowed formats: ${validExtensions.join(', ')}`);
        return;
    }

    // Prepare the data to send to Flask
    const formData = new FormData();
    formData.append('file', file);

    // Show loading state and hide old results
    loadingText.style.display = 'block';
    resultsCard.style.display = 'none';

    try {
        // Send to PyTorch model API
        const response = await fetch('/predict', {
            method: 'POST',
            body: formData
        });
        const data = await response.json();

        if (data.error) {
            alert('Backend Error: ' + data.error);
        } else {
            // 1. Populate the Prediction & Pills
            document.getElementById('verdict-text').innerText = data.prediction;
            document.getElementById('confidence-text').innerText = `Confidence: ${data.confidence}%`;
            document.getElementById('compression-text').innerText = `Provenance: ${data.compression_provenance}`;

            // 2. Dynamic Colors & Forensic Text
            const verdictEl = document.getElementById('verdict-text');
            const explanationEl = document.getElementById('explanation-text');

            // THE FIX 2: Dynamically inject the compression provenance into the explanation!
            const compText = data.compression_provenance.includes('Clean') 
                ? "In this clean, uncompressed recording" 
                : `Despite artifacts from ${data.compression_provenance.toLowerCase()}`;

            if (data.prediction === "Fake") {
                verdictEl.style.color = "var(--fake)";
                explanationEl.innerHTML = `<strong>Why it was flagged:</strong> ${compText}, the heatmap above highlights unnatural, robotic frequency bands generated by AI text-to-speech software. It lacks the organic acoustic patterns and natural breathing found in authentic human speech.`;
            } else {
                verdictEl.style.color = "var(--real)";
                explanationEl.innerHTML = `<strong>Why it passed:</strong> ${compText}, the heatmap confirms this is an authentic human voice. The highlighted regions show natural vocal formants and organic background acoustics, which are extremely difficult for AI voice generators to accurately replicate.`;
            }

            // 3. Cache-Busting Image URL Trick
            const timestamp = new Date().getTime();
            document.getElementById('heatmap-img').src = data.heatmap_url + '?t=' + timestamp;

            // 4. Reveal the final card!
            resultsCard.style.display = 'block';
        }
    } catch (error) {
        console.error('Fetch Error:', error);
        alert('An error occurred during communication with the Flask server.');
    } finally {
        // Hide loading text
        loadingText.style.display = 'none';
    }
});